#!/usr/bin/env python3
"""The cut (docs/trailer.md): writes tools/trailer/edit.json from the clip
list below. Every time in the edit (captions, score cues, the end card) is
derived from the clips' frame counts, so re-trimming a clip keeps the
captions on their shots and the score on its cuts. 60 fps; total 30 s.

Usage: cut.py  (then assemble.py preview|final)
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
FPS = 60
TOTAL = 30.0

# (shot, first frame, end frame (exclusive), options). Frame numbers are the
# Movie Maker PNG indices of trailer_out/<quality>/<shot>/.
CLIPS = [
    ("establish", 40, 220, {"fade_in": 0.6, "gain": 0.55}),   # 0 the street, rain, neon
    ("atrium", 170, 260, {"gain": 0.5}),                       # 1 the hotel, the chandeliers
    ("catcher", 40, 130, {"gain": 0.9}),                       # 2 rounds stopping in the field
    ("slide", 40, 145, {}),                                    # 3 slide launch, RX-9, Saiga
    ("slagger", 120, 232, {}),                                 # 4 charged plasma
    ("catcher", 165, 270, {}),                                 # 5 the Hatchet Man, the return
    ("gauss", 34, 70, {}),                                     # 6 the GX-4 unfolds
    ("gauss", 128, 156, {}),                                   # 7 the shot
    ("gauss_side", 146, 290, {}),                              # 8 bullet-time replay
    ("corridor", 5, 215, {"grade": "eq=brightness=0.03:gamma=1.22"}),  # 9 Governor, vault, ram
    ("dropkick", 20, 128, {}),                                 # 10 dropkick, RX-9, Governor
    ("boss", 98, 152, {}),                                     # 11 the Incense Master's cannon
    ("boss", 280, 460, {"fade_out": 0.08}),                    # 12 the execution
]
BLACK = 0.5


def main():
    clips = []
    starts = []
    t = 0.0
    for shot, a, b, opt in CLIPS:
        c = {"shot": shot, "in": a, "out": b}
        c.update(opt)
        clips.append(c)
        starts.append(t)
        t += (b - a) / FPS
    black_at = t
    clips.append({"shot": "black", "frames": int(BLACK * FPS)})
    title_at = t + BLACK
    S = starts
    captions = [
        {"text": "THEY'RE ONLY HUMAN.", "t0": 0.8, "t1": 2.85},
        {"text": "YOU'RE NOT.", "t0": S[2] + 0.05, "t1": S[3] - 0.05},
        {"style": "label", "text": "RX-9 REFLEX OVERCLOCK", "sub": "+ SAIGA-12K", "t0": S[3] + 0.25, "t1": S[4] - 0.05},
        {"style": "label", "text": "SL-9 SLAGGER", "sub": "PLASMA, CHARGED", "t0": S[4] + 0.15, "t1": S[5] - 0.05},
        {"style": "label", "text": "LC-6 LORENTZ CATCHER", "sub": "CATCH. RETURN.", "t0": S[5] + 0.1, "t1": S[6] - 0.05},
        {"style": "label", "text": "GX-4 GAUSS ARM", "sub": "ONE ROUND. THREE MEN.", "t0": S[6] + 0.1, "t1": S[9] - 0.05},
        {"style": "label", "text": "THE GOVERNOR", "sub": ".45-70 LEVER ACTION", "t0": S[9] + 0.2, "t1": S[9] + 1.9},
        {"style": "label", "text": "KR-5 RAM THRUSTERS", "t0": S[9] + 2.3, "t1": S[10] - 0.05},
        {"style": "label", "text": "THE INCENSE MASTER", "sub": "BOSS. EXECUTION.", "t0": S[11] + 0.1, "t1": S[11] + 2.2},
    ]
    edit = {
        "comment": "Generated by tools/trailer/cut.py: edit that, not this.",
        "clips": clips,
        "captions": captions,
        "title": {"duration": round(TOTAL - title_at, 4), "name": "GRAFT", "sub": "COMING SOON"},
        "score": {"reveal": S[2], "drop": S[3], "layer2": S[6], "layer3": S[9], "silence": black_at,
                  "title": title_at, "accents": [round(S[i], 3) for i in (4, 5, 6, 8, 9, 10, 11, 12)]},
        "mix": {"game": 1.0, "score": 0.75, "clip_rms_db": -19.0},
    }
    with open(os.path.join(ROOT, "tools/trailer/edit.json"), "w") as fh:
        json.dump(edit, fh, indent=1)
    for i, c in enumerate(CLIPS):
        print("%6.2f  %-11s %4d-%4d" % (S[i], c[0], c[1], c[2]))
    print("%6.2f  black\n%6.2f  title (%.2fs)" % (black_at, title_at, TOTAL - title_at))


if __name__ == "__main__":
    main()
